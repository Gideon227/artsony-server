-- Order activation: packaging proof photos and the one-time sessions that let a
-- seller upload them from a phone by scanning a QR code.

-- ── order_packaging_proofs ───────────────────────────────────────────────────
-- Evidence the seller packaged the artwork before shipment. Immutable once
-- written and capped at three photos per physical order item.

CREATE TABLE IF NOT EXISTS public.order_packaging_proofs (
  id                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_item_physical_id  UUID NOT NULL REFERENCES public.order_item_physical(id) ON DELETE CASCADE,
  order_id                UUID NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  position                SMALLINT NOT NULL CHECK (position BETWEEN 1 AND 3),
  cloudinary_public_id    TEXT NOT NULL,
  secure_url              TEXT NOT NULL,
  mime_type               TEXT NOT NULL,
  file_size_bytes         INTEGER NOT NULL CHECK (file_size_bytes > 0),
  width                   INTEGER,
  height                  INTEGER,
  uploaded_by             UUID NOT NULL REFERENCES public.users(id),
  uploaded_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (order_item_physical_id, position),
  UNIQUE (cloudinary_public_id)
);

CREATE INDEX IF NOT EXISTS idx_opp_physical_id ON public.order_packaging_proofs (order_item_physical_id);
CREATE INDEX IF NOT EXISTS idx_opp_order_id    ON public.order_packaging_proofs (order_id);

CREATE OR REPLACE RULE packaging_proof_no_update AS ON UPDATE TO public.order_packaging_proofs DO INSTEAD NOTHING;
CREATE OR REPLACE RULE packaging_proof_no_delete AS ON DELETE TO public.order_packaging_proofs DO INSTEAD NOTHING;

-- ── order_activation_sessions ────────────────────────────────────────────────
-- Only the SHA-256 hash of the token is stored; the token itself exists in the
-- QR code URL and nowhere else.

CREATE TABLE IF NOT EXISTS public.order_activation_sessions (
  id                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_item_physical_id  UUID NOT NULL REFERENCES public.order_item_physical(id) ON DELETE CASCADE,
  seller_id               UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  token_hash              TEXT NOT NULL UNIQUE,
  status                  TEXT NOT NULL DEFAULT 'PENDING'
                            CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED', 'EXPIRED', 'SUPERSEDED')),
  failure_reason          TEXT,
  expires_at              TIMESTAMPTZ NOT NULL,
  created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at            TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_oas_physical_status ON public.order_activation_sessions (order_item_physical_id, status);

-- Tracking numbers are generated by the application; this index backs the
-- uniqueness check without constraining admin-entered legacy values.
CREATE INDEX IF NOT EXISTS idx_oip_tracking_id ON public.order_item_physical (tracking_id) WHERE tracking_id IS NOT NULL;

ALTER TABLE public.order_packaging_proofs   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_activation_sessions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "deny_all_opp" ON public.order_packaging_proofs;
DROP POLICY IF EXISTS "deny_all_oas" ON public.order_activation_sessions;
CREATE POLICY "deny_all_opp" ON public.order_packaging_proofs    USING (false);
CREATE POLICY "deny_all_oas" ON public.order_activation_sessions USING (false);
